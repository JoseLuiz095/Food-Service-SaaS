import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const js=ts.transpileModule(readFileSync('src/utils/cartAvailability.ts','utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).outputText;
const {cartLineLimit,canAddWithoutOptions}=await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
const product={id:'p',trackStock:true,stockQuantity:23,stockReservedQuantity:2,optionGroups:[]};
const items=[{id:'a',productId:'p',quantity:2},{id:'b',productId:'p',quantity:1},{id:'other',productId:'q',quantity:40}];
assert.equal(cartLineLimit(product,items,'a',3),2,'other variation consumes same pickup stock');
assert.equal(cartLineLimit(product,items,'new',3),0,'all variations count for stock');
assert.equal(cartLineLimit(product,items,'new',null),0,'unknown point fails closed');
assert.equal(cartLineLimit(product,items,'a',0),0,'other point stock never substituted');
assert.equal(cartLineLimit(product,items,'a'),20,'official stock minus reservations and other lines');
assert.equal(cartLineLimit({...product,stockQuantity:0},items,'a'),99,'official made-to-order stays available');
assert.equal(cartLineLimit({...product,trackStock:false},items,'a',null),99,'digital/non-stock ignores inventory');
assert.equal(cartLineLimit({...product,stockQuantity:500},[],'a'),99,'RPC limit preserved');
assert.equal(canAddWithoutOptions(product),true);
assert.equal(canAddWithoutOptions({...product,optionGroups:[{active:true,minChoices:1}]}),false);
assert.equal(canAddWithoutOptions({...product,optionGroups:[{active:false,minChoices:1}]}),true);
assert.equal(canAddWithoutOptions({...product,optionGroups:[{active:true,minChoices:0}]}),true);
assert.equal(canAddWithoutOptions({...product,partyOrderConfig:{enabled:true}}),false);
assert.equal(canAddWithoutOptions({...product,optionGroups:[{active:false,minChoices:0,name:'__foodweb_party_order_config__'}]}),false);
console.log('14 cart availability checks passed');
